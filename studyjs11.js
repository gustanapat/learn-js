// Function แบบ Expression Function : Arrow Function
const wow = () => {
    console.log('Wow wow wow')
}

const hello = (fname, lname) => {
    console.log(`Hello ${fname} ${lname}`)
}

const sum = (n1, n2) => {
    return n1 + n2
}

let dti = wow

wow()
dti()
hello('Sombat', 'Jaidee')

console.log(sum(10, 20))